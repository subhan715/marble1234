create or replace function public.get_products(p_search text default '')
returns json language sql stable as $$
  select coalesce(json_agg(t order by lower(t.name)), '[]'::json) from (
    select p.*, coalesce(sum(i.pieces), 0) as total_pieces,
           coalesce(sum(i.total_area), 0) as total_area,
           coalesce(sum(i.total_cost_value), 0) as total_cost_value,
           coalesce(sum(i.total_value), 0) as total_value,
           count(i.id) as batch_count
      from public.products p left join public.inventory i on i.product_id = p.id
     where coalesce(p_search, '') = '' or p.name ilike '%' || p_search || '%'
        or p.material_type ilike '%' || p_search || '%' or p.color ilike '%' || p_search || '%'
     group by p.id) t
$$;

