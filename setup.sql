create or replace function public.process_order(p_order_id bigint, p_now text)
returns json language plpgsql as $$
declare o public.orders%rowtype; it public.order_items%rowtype; err text; v_no text; v_id bigint;
begin
  perform pg_advisory_xact_lock(7340501);
  select * into o from public.orders where id = p_order_id;
  if not found or o.status <> 'Pending' then raise exception 'BIZ: Order not found or already processed.'; end if;
  for it in select * from public.order_items where order_id = p_order_id order by id loop
    err := public._take_stock_area(it.inventory_id, it.area, it.item_name);
    if err is not null then raise exception 'BIZ: %', err; end if;     -- undoes every stock change above
  end loop;
  v_no := public._next_number('DEL', 'deliveries', 'delivery_no', p_now);
  insert into public.deliveries (delivery_no, order_id, invoice_id, customer_name, phone, address, status, delivery_date)
  values (v_no, p_order_id, null, o.customer_name, o.phone, o.address, 'Ready for Delivery', p_now)
  returning id into v_id;
  update public.orders set status = 'Processed' where id = p_order_id;
  return json_build_object('delivery_id', v_id, 'delivery_no', v_no);
end $$;

