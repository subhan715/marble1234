create or replace function public.get_low_stock()
returns json language sql stable as $$
  select coalesce(json_agg(t order by t.sqft_left asc), '[]'::json) from (
    select min(item_name) as item_name, max(material_type) as material_type, max(color) as color,
           sum(pieces) as pieces,
           sum(case when unit = 'Sq.Meter' then total_area * 10.7639 else total_area end) as sqft_left
      from public.inventory
     group by lower(item_name)
    having sum(case when unit = 'Sq.Meter' then total_area * 10.7639 else total_area end) < 100) t
$$;

create or replace function public.get_dashboard_stats(p_today text)
returns json language plpgsql stable as $$
declare
  v_items bigint; v_pieces numeric; v_area float8; v_value float8; v_invest float8; v_low integer;
  v_pending bigint; v_today_sales float8; v_today_profit float8; v_today_count bigint;
  v_all_profit float8; v_all_sales float8; v_pdel bigint;
begin
  select count(distinct lower(item_name)), coalesce(sum(pieces), 0),
         coalesce(sum(case when unit = 'Sq.Meter' then total_area * 10.7639 else total_area end), 0),
         coalesce(sum(total_value), 0), coalesce(sum(total_cost_value), 0)
    into v_items, v_pieces, v_area, v_value, v_invest from public.inventory;
  select json_array_length(public.get_low_stock()) into v_low;
  select count(*) into v_pending from public.orders where status = 'Pending';
  select coalesce(sum(total_amount), 0), coalesce(sum(total_profit), 0), count(*)
    into v_today_sales, v_today_profit, v_today_count from public.invoices where invoice_date like p_today || '%';
  select coalesce(sum(total_profit), 0), coalesce(sum(total_amount), 0) into v_all_profit, v_all_sales from public.invoices;
  select count(*) into v_pdel from public.deliveries where status <> 'Delivered';
  return json_build_object('total_items', v_items, 'total_pieces', v_pieces, 'total_area', v_area,
    'total_value', v_value, 'total_investment', v_invest, 'potential_profit', v_value - v_invest,
    'low_stock', v_low, 'pending_orders', v_pending, 'today_sales', v_today_sales,
    'today_profit', v_today_profit, 'today_count', v_today_count,
    'total_profit_alltime', v_all_profit, 'total_sales_alltime', v_all_sales, 'pending_deliveries', v_pdel);
end $$;

