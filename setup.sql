create or replace function public.create_pos_sale(p_customer text, p_phone text, p_payment text, p_items json, p_now text, p_transport double precision default 0, p_services text default '',
       p_rft_ft double precision default 0, p_rft_rate double precision default 0,
       p_tip double precision default 0, p_rft_in1 double precision default 0, p_rft_in2 double precision default 0)
returns json language plpgsql as $$
declare v jsonb; it jsonb; err text; v_no text; v_total float8 := 0; v_profit float8 := 0; v_cost float8; v_inv bigint;
begin
  perform pg_advisory_xact_lock(7340501);
  v := public._verify_cart(p_items);
  for it in select value from jsonb_array_elements(v) loop
    err := public._take_stock_area((it->>'inventory_id')::bigint, (it->>'area')::float8, it->>'item_name');
    if err is not null then raise exception 'BIZ: %', err; end if;
  end loop;
  v_no := public._next_number('INV', 'invoices', 'invoice_no', p_now);
  for it in select value from jsonb_array_elements(v) loop
    select coalesce(purchase_price_per_unit, 0) into v_cost from public.inventory where id = (it->>'inventory_id')::bigint;
    if not found then v_cost := 0; end if;
    v_total := v_total + (it->>'amount')::float8;
    v_profit := v_profit + ((it->>'price_per_unit')::float8 - v_cost) * (it->>'area')::float8;
  end loop;
  insert into public.invoices (invoice_no, source, order_id, customer_name, phone, payment_method, invoice_date, total_amount, total_profit, transport, services, rft_ft, rft_rate, rft_amount, tip, rft_in1, rft_in2)
  values (v_no, 'POS', null, p_customer, p_phone, p_payment, p_now, v_total, v_profit, greatest(coalesce(p_transport, 0), 0), public._clean_services(p_services),
          public._rft_calc(p_services, p_rft_in1, p_rft_in2, p_rft_ft), public._rft_val(p_services, p_rft_rate), public._rft_amount(p_services, p_rft_in1, p_rft_in2, p_rft_ft, p_rft_rate),
          greatest(coalesce(p_tip, 0), 0), public._rft_in(p_services, p_rft_in1), public._rft_in(p_services, p_rft_in2)) returning id into v_inv;
  for it in select value from jsonb_array_elements(v) loop
    select coalesce(purchase_price_per_unit, 0) into v_cost from public.inventory where id = (it->>'inventory_id')::bigint;
    if not found then v_cost := 0; end if;
    insert into public.invoice_items (invoice_id, inventory_id, item_name, pieces, width, length, unit, area, price_per_unit, cost_price_per_unit, amount, profit)
    values (v_inv, (it->>'inventory_id')::bigint, it->>'item_name', (it->>'pieces')::integer, (it->>'width')::float8,
            (it->>'length')::float8, it->>'unit', (it->>'area')::float8, (it->>'price_per_unit')::float8, v_cost,
            (it->>'amount')::float8, ((it->>'price_per_unit')::float8 - v_cost) * (it->>'area')::float8);
  end loop;
  return json_build_object('invoice_id', v_inv);
end $$;

