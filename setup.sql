create or replace function public.get_delivery(p_id bigint)
returns json language plpgsql stable as $$
declare d public.deliveries%rowtype; v_items json := '[]'::json; v_inv json; v_ord json;
begin
  select * into d from public.deliveries where id = p_id;
  if not found then return json_build_object('delivery', null, 'items', '[]'::json, 'invoice', null, 'order', null); end if;
  if d.invoice_id is not null then
    select coalesce(json_agg(x order by x.id), '[]'::json) into v_items from public.invoice_items x where x.invoice_id = d.invoice_id;
    select row_to_json(i) into v_inv from public.invoices i where i.id = d.invoice_id;
  end if;
  if d.order_id is not null then
    select row_to_json(o) into v_ord from public.orders o where o.id = d.order_id;
    if json_array_length(v_items) = 0 then
      select coalesce(json_agg(x order by x.id), '[]'::json) into v_items from public.order_items x where x.order_id = d.order_id;
    end if;
  end if;
  return json_build_object('delivery', row_to_json(d), 'items', v_items, 'invoice', v_inv, 'order', v_ord);
end $$;

create or replace function public.update_delivery_status(p_id bigint, p_status text, p_now text)
returns json language plpgsql as $$
declare v_inv bigint;
begin
  perform pg_advisory_xact_lock(7340501);
  update public.deliveries set status = p_status where id = p_id;
  if p_status = 'Delivered' then v_inv := public._generate_invoice(p_id, p_now); end if;
  return json_build_object('invoice_id', v_inv);
end $$;

