create or replace function public.get_or_create_product(p json, p_now text)
returns json language plpgsql as $$
declare existing public.products%rowtype; new_id bigint;
begin
  perform pg_advisory_xact_lock(7340501);
  select * into existing from public.products where lower(name) = lower(p->>'name');
  if found then return json_build_object('id', existing.id, 'created', false); end if;
  insert into public.products (name, material_type, color, unit, purchase_price_per_unit, selling_price_per_unit, supplier, notes, date_added)
  values (p->>'name', p->>'material_type', p->>'color', p->>'unit', (p->>'purchase_price_per_unit')::float8,
          (p->>'selling_price_per_unit')::float8, p->>'supplier', p->>'notes', p_now)
  returning id into new_id;
  return json_build_object('id', new_id, 'created', true);
end $$;

