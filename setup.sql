-- ---------- orders ----------
-- keeps only the four allowed services, in a fixed order, whatever the browser sends
create or replace function public._clean_services(p text)
returns text language sql immutable as $$
  select coalesce(string_agg(s, ', ' order by ord), '')
    from unnest(array['Laap', 'Gola', 'Polishing', 'Finishing']) with ordinality as a(s, ord)
   where exists (select 1 from unnest(string_to_array(coalesce(p, ''), ',')) x where lower(trim(x)) = lower(s))
$$;

