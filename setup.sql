create or replace function public.db_size_kb()
returns json language sql stable as $$
  select to_json(round((coalesce(sum(pg_total_relation_size(c.oid)), 0) / 1024.0)::numeric, 1))
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind = 'r'
$$;

create or replace function public.export_all()
returns json language plpgsql security definer set search_path = public as $$
begin
  if not public._is_boss() then raise exception 'BIZ: Only the boss can use Backup and Restore.'; end if;
  return json_build_object(
    'products',      (select coalesce(json_agg(t order by id), '[]'::json) from public.products t),
    'inventory',     (select coalesce(json_agg(t order by id), '[]'::json) from public.inventory t),
    'orders',        (select coalesce(json_agg(t order by id), '[]'::json) from public.orders t),
    'order_items',   (select coalesce(json_agg(t order by id), '[]'::json) from public.order_items t),
    'invoices',      (select coalesce(json_agg(t order by id), '[]'::json) from public.invoices t),
    'invoice_items', (select coalesce(json_agg(t order by id), '[]'::json) from public.invoice_items t),
    'deliveries',    (select coalesce(json_agg(t order by id), '[]'::json) from public.deliveries t),
    'drawings',      (select coalesce(json_agg(t order by filename), '[]'::json) from public.drawings t));
end $$;

-- replaces ALL data with the backup (all or nothing)
create or replace function public.restore_all(p json)
returns json language plpgsql security definer set search_path = public as $$
declare t text;
begin
  if not public._is_boss() then raise exception 'BIZ: Only the boss can use Backup and Restore.'; end if;
  perform pg_advisory_xact_lock(7340501);
  delete from public.order_items;  delete from public.invoice_items;
  delete from public.deliveries;   delete from public.invoices;
  delete from public.orders;       delete from public.inventory;
  delete from public.products;     delete from public.drawings;
  insert into public.products      select * from json_populate_recordset(null::public.products,      coalesce(p->'products', '[]'::json));
  insert into public.inventory     select * from json_populate_recordset(null::public.inventory,     coalesce(p->'inventory', '[]'::json));
  insert into public.orders        select * from json_populate_recordset(null::public.orders,        coalesce(p->'orders', '[]'::json));
  insert into public.order_items   select * from json_populate_recordset(null::public.order_items,   coalesce(p->'order_items', '[]'::json));
  insert into public.invoices      select * from json_populate_recordset(null::public.invoices,      coalesce(p->'invoices', '[]'::json));
  insert into public.invoice_items select * from json_populate_recordset(null::public.invoice_items, coalesce(p->'invoice_items', '[]'::json));
  insert into public.deliveries    select * from json_populate_recordset(null::public.deliveries,    coalesce(p->'deliveries', '[]'::json));
  insert into public.drawings      select * from json_populate_recordset(null::public.drawings,      coalesce(p->'drawings', '[]'::json));
  foreach t in array array['products','inventory','orders','order_items','invoices','invoice_items','deliveries'] loop
    execute format('select setval(pg_get_serial_sequence(%L, ''id''), greatest((select coalesce(max(id), 0) from public.%I), 1), (select count(*) > 0 from public.%I))', 'public.' || t, t, t);
  end loop;
  return json_build_object('ok', true);
end $$;

-- ---------- product-wise sales report ----------
create or replace function public.get_product_sales(p_search text default '')
returns json language sql stable as $$
  with m as (
    select ii.id, ii.invoice_id, ii.item_name, ii.pieces, ii.width, ii.length, ii.unit, ii.area,
           ii.price_per_unit, ii.amount, ii.profit, i.invoice_no, i.invoice_date, i.customer_name, i.source
      from public.invoice_items ii join public.invoices i on i.id = ii.invoice_id
     where coalesce(p_search, '') = '' or ii.item_name ilike '%' || p_search || '%'
  )
  select json_build_object(
    'summary', (select coalesce(json_agg(s order by s.last_sale desc), '[]'::json) from (
                  select item_name, count(distinct invoice_id) as bills, sum(pieces) as pieces, sum(area) as area,
                         max(unit) as unit, sum(amount) as amount, sum(coalesce(profit, 0)) as profit, max(invoice_date) as last_sale
                    from m group by item_name order by max(invoice_date) desc limit 100) s),
    'rows',    (select coalesce(json_agg(r order by r.invoice_id desc, r.id desc), '[]'::json) from (
                  select * from m where coalesce(p_search, '') <> '' order by invoice_id desc, id desc limit 200) r))
$$;

-- ---------- deleting records (boss only; stock is NOT changed) ----------
create or replace function public.delete_invoice(p_id bigint)
returns json language plpgsql security definer set search_path = public as $$
begin
  if not public._is_boss() then raise exception 'BIZ: Only the boss can delete records.'; end if;
  perform pg_advisory_xact_lock(7340501);
  update public.deliveries set invoice_id = null where invoice_id = p_id;
  delete from public.invoices where id = p_id;                 -- its items go with it
  return json_build_object('ok', true);
end $$;

