-- ---------- invoices ----------
create or replace function public._generate_invoice(p_delivery_id bigint, p_now text)
returns bigint language plpgsql as $$
declare d public.deliveries%rowtype; o public.orders%rowtype; it public.order_items%rowtype;
        v_no text; v_total float8 := 0; v_profit float8 := 0; v_cost float8; v_line float8; v_inv bigint; n integer;
begin
  select * into d from public.deliveries where id = p_delivery_id;
  if not found or d.invoice_id is not null or d.order_id is null then return null; end if;
  select * into o from public.orders where id = d.order_id;
  if not found then return null; end if;
  select count(*) into n from public.order_items where order_id = d.order_id;
  if n = 0 then return null; end if;
  v_no := public._next_number('INV', 'invoices', 'invoice_no', p_now);
  for it in select * from public.order_items where order_id = d.order_id order by id loop
    select coalesce(purchase_price_per_unit, 0) into v_cost from public.inventory where id = it.inventory_id;
    if not found then v_cost := 0; end if;
    v_total := v_total + it.amount;
    v_profit := v_profit + (it.price_per_unit - v_cost) * it.area;
  end loop;
  insert into public.invoices (invoice_no, source, order_id, customer_name, phone, payment_method, invoice_date, total_amount, total_profit, transport, services, rft_ft, rft_rate, rft_amount, tip, rft_in1, rft_in2)
  values (v_no, 'Order', o.id, o.customer_name, o.phone, 'Unpaid', p_now, v_total, v_profit, coalesce(o.transport, 0), coalesce(o.services, ''),
          coalesce(o.rft_ft, 0), coalesce(o.rft_rate, 0), coalesce(o.rft_amount, 0), coalesce(o.tip, 0), coalesce(o.rft_in1, 0), coalesce(o.rft_in2, 0)) returning id into v_inv;
  for it in select * from public.order_items where order_id = d.order_id order by id loop
    select coalesce(purchase_price_per_unit, 0) into v_cost from public.inventory where id = it.inventory_id;
    if not found then v_cost := 0; end if;
    v_line := (it.price_per_unit - v_cost) * it.area;
    insert into public.invoice_items (invoice_id, inventory_id, item_name, pieces, width, length, unit, area, price_per_unit, cost_price_per_unit, amount, profit)
    values (v_inv, it.inventory_id, it.item_name, it.pieces, it.width, it.length, it.unit, it.area, it.price_per_unit, v_cost, it.amount, v_line);
  end loop;
  update public.deliveries set invoice_id = v_inv where id = p_delivery_id;
  return v_inv;
end $$;

