-- =====================================================================
--  business logic (ported 1:1 from the original db.py)
--  Every function that changes data runs as ONE transaction and takes a
--  lock, so two people working at the same time cannot oversell stock or
--  get the same invoice number.
--  p_now = the shop computer's local time 'YYYY-MM-DD HH:MM'
-- =====================================================================

create or replace function public._next_number(p_prefix text, p_table text, p_col text, p_now text)
returns text language plpgsql as $$
declare c bigint; today text := replace(left(p_now, 10), '-', '');
begin
  execute format('select count(*) from public.%I where %I like %L', p_table, p_col, p_prefix || '-' || today || '-%') into c;
  return p_prefix || '-' || today || '-' || lpad((c + 1)::text, 3, '0');
end $$;

-- checks the cart sent by the browser, recalculates area & amount on the server
create or replace function public._verify_cart(p_items json)
returns jsonb language plpgsql as $$
declare
  it json; inv public.inventory%rowtype; res jsonb := '[]'::jsonb;
  v_inv bigint; v_pieces integer; v_price float8; v_w float8; v_l float8; v_waste float8;
  app float8; v_area float8; v_amount float8;
begin
  if p_items is null or json_typeof(p_items) <> 'array' then raise exception 'INVALID: cart'; end if;
  for it in select value from json_array_elements(p_items) loop
    v_inv    := (it->>'inventory_id')::bigint;
    v_pieces := (it->>'pieces')::integer;
    v_price  := (it->>'price_per_unit')::float8;
    if v_inv is null or v_pieces is null or v_price is null then raise exception 'INVALID: missing field'; end if;
    if v_pieces <= 0 then raise exception 'INVALID: Every item''s quantity must be greater than zero.'; end if;
    if v_price < 0 then raise exception 'INVALID: Item price cannot be negative.'; end if;
    select * into inv from public.inventory where id = v_inv;
    if not found then raise exception 'INVALID: One of the items no longer exists in inventory. Please refresh and try again.'; end if;
    v_w     := coalesce((it->>'width')::float8,  inv.width);
    v_l     := coalesce((it->>'length')::float8, inv.length);
    v_waste := coalesce(nullif(it->>'waste', '')::float8, 0);
    if v_w is null or v_l is null then raise exception 'INVALID: Width, Length and Waste must be numbers.'; end if;
    if v_w <= 0 or v_l <= 0 then raise exception 'INVALID: Width and Length must be greater than zero.'; end if;
    if v_waste < 0 then raise exception 'INVALID: Waste cannot be negative.'; end if;
    if inv.unit = 'Sq.Ft' then app := (v_w * v_l) / 144.0;
    else app := (v_w * 0.0254) * (v_l * 0.0254); end if;
    v_area   := app * v_pieces + v_waste;
    v_amount := round((v_area * v_price)::numeric, 2)::float8;
    res := res || jsonb_build_object('inventory_id', v_inv, 'item_name', inv.item_name, 'pieces', v_pieces,
             'width', v_w, 'length', v_l, 'unit', inv.unit, 'waste', v_waste, 'area', v_area,
             'price_per_unit', v_price, 'amount', v_amount);
  end loop;
  return res;
end $$;

-- takes `p_area` out of the product's stock batches (the chosen batch first, then older ones)
-- returns an error text, or NULL when the stock was deducted
create or replace function public._take_stock_area(p_inv bigint, p_area float8, p_item_name text)
returns text language plpgsql as $$
declare
  ref public.inventory%rowtype; b public.inventory%rowtype;
  avail float8; remaining float8; take float8; new_area float8; per_piece float8; new_pieces integer;
  eps constant float8 := 1e-6;
begin
  select * into ref from public.inventory where id = p_inv;
  if not found then return 'One of the items no longer exists in inventory. Please refresh and try again.'; end if;

  select coalesce(sum(total_area), 0) into avail from public.inventory
   where unit = ref.unit and ((ref.product_id is not null and product_id = ref.product_id)
                          or (ref.product_id is null and lower(item_name) = lower(ref.item_name)));
  if p_area > avail + eps then
    return format('Insufficient Stock: "%s" needs %s %s, only %s %s available.', p_item_name,
                  trim(to_char(round(p_area::numeric, 2), 'FM9999999990.00')), ref.unit,
                  trim(to_char(round(avail::numeric, 2), 'FM9999999990.00')), ref.unit);
  end if;

  remaining := p_area;
  for b in select * from public.inventory
            where unit = ref.unit and ((ref.product_id is not null and product_id = ref.product_id)
                                   or (ref.product_id is null and lower(item_name) = lower(ref.item_name)))
            order by (id = p_inv) desc, date_added, id for update
  loop
    if remaining <= eps then return null; end if;
    take := least(remaining, coalesce(b.total_area, 0));
    if take <= 0 then continue; end if;
    new_area := coalesce(b.total_area, 0) - take;
    if new_area < eps then new_area := 0; end if;
    per_piece := coalesce(b.area_per_piece, 0);
    if per_piece > 0 and new_area > 0 then new_pieces := ceil(round((new_area / per_piece)::numeric, 6))::integer;
    else new_pieces := 0; end if;
    update public.inventory
       set pieces = new_pieces, total_area = new_area,
           total_cost_value = new_area * coalesce(b.purchase_price_per_unit, 0),
           total_value      = new_area * coalesce(b.selling_price_per_unit, 0)
     where id = b.id;
    remaining := remaining - take;
  end loop;
  return null;
end $$;

