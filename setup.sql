create or replace function public.delete_order(p_id bigint)
returns json language plpgsql security definer set search_path = public as $$
declare v_draw text;
begin
  if not public._is_boss() then raise exception 'BIZ: Only the boss can delete records.'; end if;
  perform pg_advisory_xact_lock(7340501);
  select drawing_filename into v_draw from public.orders where id = p_id;
  update public.deliveries set order_id = null where order_id = p_id;
  update public.invoices   set order_id = null where order_id = p_id;
  delete from public.orders where id = p_id;                   -- its items go with it
  if v_draw is not null and not exists (select 1 from public.orders where drawing_filename = v_draw) then
    delete from public.drawings where filename = v_draw;
  end if;
  return json_build_object('ok', true);
end $$;

