-- running ft / cost per ft: never negative, and zero when no service is ticked
create or replace function public._rft_val(p_services text, p_v double precision)
returns double precision language sql immutable as $$
  select case when public._clean_services(p_services) = '' then 0 else greatest(coalesce(p_v, 0), 0) end
$$;
drop function if exists public._rft_amount(text, double precision, double precision);
-- Laap or Gola ticked: Customer RFT = inches1 x inches2 / 12.  Only Polishing/Finishing: Customer RFT is typed in.
create or replace function public._rft_inches_mode(p_services text)
returns boolean language sql immutable as $$
  select public._clean_services(p_services) ~ '(Laap|Gola)'
$$;
create or replace function public._rft_in(p_services text, p_v double precision)
returns double precision language sql immutable as $$
  select case when public._rft_inches_mode(p_services) then greatest(coalesce(p_v, 0), 0) else 0 end
$$;
create or replace function public._rft_calc(p_services text, p_in1 double precision, p_in2 double precision, p_ft double precision)
returns double precision language sql immutable as $$
  select case when public._clean_services(p_services) = '' then 0
              when public._rft_inches_mode(p_services) then greatest(coalesce(p_in1, 0), 0) * greatest(coalesce(p_in2, 0), 0) / 12.0
              else greatest(coalesce(p_ft, 0), 0) end
$$;
create or replace function public._rft_amount(p_services text, p_in1 double precision, p_in2 double precision, p_ft double precision, p_rate double precision)
returns double precision language sql immutable as $$
  select round((public._rft_calc(p_services, p_in1, p_in2, p_ft) * public._rft_val(p_services, p_rate))::numeric, 2)::float8
$$;

create or replace function public.create_order(p_customer text, p_phone text, p_address text, p_notes text,
       p_items json, p_drawing_filename text, p_drawing_notes text, p_now text, p_transport double precision default 0, p_services text default '',
       p_rft_ft double precision default 0, p_rft_rate double precision default 0,
       p_tip double precision default 0, p_rft_in1 double precision default 0, p_rft_in2 double precision default 0)
returns json language plpgsql as $$
declare v jsonb; it jsonb; v_no text; v_total float8 := 0; v_id bigint;
begin
  perform pg_advisory_xact_lock(7340501);
  v := public._verify_cart(p_items);
  v_no := public._next_number('ORD', 'orders', 'order_no', p_now);
  for it in select value from jsonb_array_elements(v) loop v_total := v_total + (it->>'amount')::float8; end loop;
  insert into public.orders (order_no, customer_name, phone, address, status, order_date, notes, total_amount, drawing_filename, drawing_notes, transport, services, rft_ft, rft_rate, rft_amount, tip, rft_in1, rft_in2)
  values (v_no, p_customer, p_phone, p_address, 'Pending', p_now, p_notes, v_total, p_drawing_filename, p_drawing_notes, greatest(coalesce(p_transport, 0), 0), public._clean_services(p_services),
          public._rft_calc(p_services, p_rft_in1, p_rft_in2, p_rft_ft), public._rft_val(p_services, p_rft_rate), public._rft_amount(p_services, p_rft_in1, p_rft_in2, p_rft_ft, p_rft_rate),
          greatest(coalesce(p_tip, 0), 0), public._rft_in(p_services, p_rft_in1), public._rft_in(p_services, p_rft_in2))
  returning id into v_id;
  for it in select value from jsonb_array_elements(v) loop
    insert into public.order_items (order_id, inventory_id, item_name, pieces, width, length, unit, area, price_per_unit, amount)
    values (v_id, (it->>'inventory_id')::bigint, it->>'item_name', (it->>'pieces')::integer, (it->>'width')::float8,
            (it->>'length')::float8, it->>'unit', (it->>'area')::float8, (it->>'price_per_unit')::float8, (it->>'amount')::float8);
  end loop;
  return json_build_object('order_id', v_id, 'order_no', v_no);
end $$;

